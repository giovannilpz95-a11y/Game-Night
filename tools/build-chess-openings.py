#!/usr/bin/env python3
"""Builds the Chess opening book for Game Review into src/shared/ChessData/.

    pip install chess
    python3 tools/build-chess-openings.py path/to/chess-openings   # folder with a.tsv .. e.tsv

Source: lichess-org/chess-openings (https://github.com/lichess-org/chess-openings), public
domain / CC0. 3,800+ named lines, each "eco<TAB>name<TAB>pgn".

Every position on every line goes in the book, keyed by a hash of its piece placement plus
the side to move (so transpositions find the same opening). Positions at the end of a line
carry that line's name; positions on the way carry none (the review keeps the last name it
saw). The hash must match ChessOpenings.key in src/shared/ChessReview.luau: two 32-bit
FNV-1a hashes (the key string forwards and backwards), each written as 6 base-64 digits.

Output (two modules, each well under Roblox's 200k-character script limit):
  ChessOpeningNames.luau  { "Amar Opening", ... }
  ChessOpeningBook.luau   one long string, 14 characters per position: 12 key + 2 name index
"""

import os
import sys

import chess
import chess.pgn  # noqa: F401  (keeps the import obvious for readers)

DIGITS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"


def fnv1a(text: str) -> int:
    h = 2166136261
    for byte in text.encode("utf-8"):
        h ^= byte
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def b64(value: int, width: int) -> str:
    out = ""
    for _ in range(width):
        out = DIGITS[value % 64] + out
        value //= 64
    return out


def key_of(board: chess.Board) -> str:
    text = board.board_fen() + (" w" if board.turn == chess.WHITE else " b")
    return b64(fnv1a(text), 6) + b64(fnv1a(text[::-1]), 6)


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else "."
    rows = []
    for letter in "abcde":
        with open(os.path.join(src, f"{letter}.tsv"), encoding="utf-8") as f:
            next(f)  # header
            for line in f:
                line = line.rstrip("\n")
                if not line:
                    continue
                eco, name, pgn = line.split("\t")
                rows.append((eco, name, pgn))

    names: list[str] = []
    name_index: dict[str, int] = {}
    named: dict[str, int] = {}  # key -> name index (1-based)
    plies_of: dict[str, int] = {}  # key -> ply count of the line that named it
    on_line: set[str] = set()
    for eco, name, pgn in rows:
        board = chess.Board()
        tokens = [t for t in pgn.split() if not t.endswith(".")]
        for san in tokens:
            board.push_san(san)
            on_line.add(key_of(board))
        if name not in name_index:
            names.append(name)
            name_index[name] = len(names)
        k = key_of(board)
        # Several lines can reach one position; the shortest line's name wins (Lichess's rule).
        if k not in named or len(tokens) < plies_of[k]:
            named[k] = name_index[name]
            plies_of[k] = len(tokens)

    records = []
    for k in sorted(on_line):
        records.append(k + b64(named.get(k, 0), 2))
    assert len(names) < 64 * 64

    out_dir = os.path.join(os.path.dirname(__file__), "..", "src", "shared", "ChessData")
    header = "-- Generated by tools/build-chess-openings.py from lichess-org/chess-openings (CC0). Don't edit by hand.\n"
    with open(os.path.join(out_dir, "ChessOpeningNames.luau"), "w", encoding="utf-8") as f:
        f.write(header)
        f.write("return {\n")
        for n in names:
            f.write("\t" + '"' + n.replace("\\", "\\\\").replace('"', '\\"') + '",\n')
        f.write("}\n")
    with open(os.path.join(out_dir, "ChessOpeningBook.luau"), "w", encoding="utf-8") as f:
        f.write(header)
        f.write("-- 14 characters per book position: 12-character position key, 2-character name index (AA = no name).\n")
        f.write("return table.concat({\n")
        for i in range(0, len(records), 40):
            f.write('\t"' + "".join(records[i : i + 40]) + '",\n')
        f.write("})\n")
    print(f"{len(names)} names, {len(records)} book positions")


if __name__ == "__main__":
    main()
