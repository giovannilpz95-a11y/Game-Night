// Builds the Word Tiles dictionary into src/server/Data/WordList/.
//
//   node tools/build-word-list.mjs path/to/enable1.txt
//
// Source: the ENABLE word list (public domain), e.g.
// https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
// Words with offensive meanings are dropped using tools/word-blocklist.rot13.txt (`keep` lines
// put back clean words a `contains` or `family` rule would catch, like SPICES or BASEMENT), and words
// longer than the biggest board (15) are dropped because they can never be played.
//
// Output is front-coded to keep it small: each word is one uppercase letter giving how many
// letters it shares with the word before it (A = 0, B = 1, ...), then the rest of the word in
// lowercase. Newlines are ignored. src/shared/WordTrie.luau decodes it.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const source = process.argv[2]
if (!source) {
  console.error('usage: node tools/build-word-list.mjs path/to/enable1.txt')
  process.exit(1)
}

const MAX_LENGTH = 15
const PART_CHARS = 90000
const ENDINGS = ['', 's', 'es', 'd', 'ed', 'ing', 'er', 'ers', 'y', 'ier', 'iest', 'ies', 'iness', 'ish', 'ly', 'head', 'heads', 'hole', 'holes']

const rot13 = (s) => s.replace(/[a-z]/g, (c) => String.fromCharCode(((c.charCodeAt(0) - 97 + 13) % 26) + 97))
const contains = []
const family = new Set()
const keep = new Set()
for (const line of readFileSync(join(root, 'tools', 'word-blocklist.rot13.txt'), 'utf8').split('\n')) {
  const [kind, ...rest] = line.trim().split(/\s+/)
  if (!kind || kind.startsWith('#') || rest.length === 0) continue
  for (const word of rest) {
    const plain = rot13(word)
    if (kind === 'contains') contains.push(plain)
    else if (kind === 'family') for (const end of ENDINGS) family.add(plain + end)
    else if (kind === 'word') family.add(plain)
    else if (kind === 'keep') keep.add(plain)
    else throw new Error(`word-blocklist: unknown kind "${kind}"`)
  }
}
const blocked = (w) => !keep.has(w) && (family.has(w) || contains.some((bad) => w.includes(bad)))

const words = [...new Set(readFileSync(source, 'utf8').split(/\r?\n/).map((w) => w.trim().toLowerCase()))]
  .filter((w) => /^[a-z]{2,}$/.test(w) && w.length <= MAX_LENGTH)
  .filter((w) => !blocked(w))
  .sort()

let encoded = ''
let previous = ''
for (const word of words) {
  let shared = 0
  while (shared < previous.length && shared < word.length && previous[shared] === word[shared]) shared++
  encoded += String.fromCharCode(65 + shared) + word.slice(shared)
  previous = word
}

const outDir = join(root, 'src', 'server', 'Data', 'WordList')
mkdirSync(outDir, { recursive: true })
for (const name of readdirSync(outDir)) unlinkSync(join(outDir, name))

// Split at word starts so each part stays a manageable script size.
const parts = []
let start = 0
while (start < encoded.length) {
  let end = Math.min(encoded.length, start + PART_CHARS)
  while (end < encoded.length && !/[A-Z]/.test(encoded[end])) end++
  parts.push(encoded.slice(start, end))
  start = end
}
const header = '-- Generated by tools/build-word-list.mjs from the ENABLE word list (public domain). Do not edit.\n'
parts.forEach((part, i) => {
  const lines = part.match(/.{1,120}/g).join('\n')
  writeFileSync(join(outDir, `Part${String(i + 1).padStart(2, '0')}.luau`), `${header}return [[\n${lines}\n]]\n`)
})
writeFileSync(
  join(outDir, 'init.luau'),
  `${header}-- The Word Tiles dictionary as one front-coded string (see WordTrie.fromEncoded).\n` +
    `-- ${words.length} words.\n\n` +
    `local parts = {}\nfor i = 1, ${parts.length} do\n\ttable.insert(parts, require(script:FindFirstChild(string.format("Part%02d", i)) :: any))\nend\nreturn table.concat(parts)\n`,
)
console.log(`${words.length} words, ${encoded.length} chars, ${parts.length} parts`)
